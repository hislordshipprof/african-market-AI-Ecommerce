// Writes the Gazetteer seed migration for the Store directory near-me search (#452).
// Run once, by hand, from the Census national files (pipe-delimited .txt inside the zips):
//   tsx scripts/gazetteer-migration.ts <zcta.txt> <place.txt> > prisma/migrations/<name>/migration.sql
// The app never downloads these files (ADR-0017).
import { readFileSync } from "node:fs";
import { gazetteerPlaceName, placeKey } from "../src/lib/directory/near-query";
import { isStateCode } from "../src/lib/directory/us-states";

const SOURCE = "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/";
const DOWNLOADED = "2026-11-14";
const BATCH = 1000;

function rows(path: string): Record<string, string>[] {
  const [head, ...lines] = readFileSync(path, "utf8").trim().split(/\r?\n/);
  const cols = head!.split("|").map((c) => c.trim());
  return lines.map((line) => Object.fromEntries(line.split("|").map((v, i) => [cols[i], v.trim()])));
}

const coord = (v: string) => Number(v).toFixed(6).replace(/\.?0+$/, "");
const text = (v: string) => `'${v.replace(/'/g, "''")}'`;

function inserts(table: string, cols: string, values: string[]): string {
  const out: string[] = [];
  for (let i = 0; i < values.length; i += BATCH) {
    out.push(`INSERT INTO "${table}" (${cols}) VALUES\n${values.slice(i, i + BATCH).join(",\n")};`);
  }
  return out.join("\n");
}

const [zctaPath, placePath] = process.argv.slice(2);
if (!zctaPath || !placePath) throw new Error("usage: gazetteer-migration.ts <zcta.txt> <place.txt>");

// Territories (PR, VI, Guam, the Marianas, American Samoa) are outside the platform's states (ADR-0001).
const TERRITORY_ZIP = /^(00[6-9]|969|96799)/;
// How far from its centroid a ZIP still counts: 1.5 × the radius of a circle of its area, plus 3 miles.
const reach = (r: Record<string, string>) =>
  (Math.sqrt((Number(r.ALAND_SQMI) + Number(r.AWATER_SQMI)) / Math.PI) * 1.5 + 3).toFixed(1);
const zips = rows(zctaPath).filter((r) => !TERRITORY_ZIP.test(r.GEOID!)).map((r) => `(${text(r.GEOID!)},${coord(r.INTPTLAT!)},${coord(r.INTPTLONG!)},${reach(r)})`);

// One row per state and name: an incorporated place beats a CDP, then the larger land area wins.
const places = new Map<string, { state: string; key: string; name: string; lat: string; lng: string; rank: [number, number] }>();
for (const r of rows(placePath)) {
  if (!isStateCode(r.USPS!)) continue;
  const name = gazetteerPlaceName(r.NAME!, r.LSAD!);
  const key = placeKey(name);
  const rank: [number, number] = [r.FUNCSTAT === "A" ? 1 : 0, Number(r.ALAND)];
  const id = `${r.USPS}|${key}`;
  const seen = places.get(id);
  if (seen && (seen.rank[0] > rank[0] || (seen.rank[0] === rank[0] && seen.rank[1] >= rank[1]))) continue;
  places.set(id, { state: r.USPS!, key, name, lat: coord(r.INTPTLAT!), lng: coord(r.INTPTLONG!), rank });
}
const placeValues = [...places.values()]
  .sort((a, b) => a.state.localeCompare(b.state) || a.key.localeCompare(b.key))
  .map((p) => `(${text(p.state)},${text(p.key)},${text(p.name)},${p.lat},${p.lng})`);

process.stdout.write(`-- Store directory near me (#452): US Census Gazetteer ZCTA and place centroids.
-- Source: ${SOURCE} (2025_Gaz_zcta_national.zip, 2025_Gaz_place_national.zip), downloaded ${DOWNLOADED}.
-- Generated by scripts/gazetteer-migration.ts. Static data: the app only reads it (ADR-0017).
-- ZIPs and places cover the 50 states and DC; one place row per state and name.

CREATE TABLE "gazetteer_zips" (
    "zip" TEXT NOT NULL,
    "lat" DOUBLE PRECISION NOT NULL,
    "lng" DOUBLE PRECISION NOT NULL,
    "reach_mi" DOUBLE PRECISION NOT NULL,
    CONSTRAINT "gazetteer_zips_pkey" PRIMARY KEY ("zip")
);

CREATE TABLE "gazetteer_places" (
    "state" TEXT NOT NULL,
    "name_key" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "lat" DOUBLE PRECISION NOT NULL,
    "lng" DOUBLE PRECISION NOT NULL,
    CONSTRAINT "gazetteer_places_pkey" PRIMARY KEY ("state", "name_key")
);

CREATE INDEX "gazetteer_places_name_key_idx" ON "gazetteer_places"("name_key");
CREATE INDEX "gazetteer_zips_lat_idx" ON "gazetteer_zips"("lat");

${inserts("gazetteer_zips", `"zip","lat","lng","reach_mi"`, zips)}

${inserts("gazetteer_places", `"state","name_key","name","lat","lng"`, placeValues)}

-- Public reference data: every role reads it, nobody at runtime writes it.
ALTER TABLE "gazetteer_zips" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "gazetteer_zips" FORCE ROW LEVEL SECURITY;
CREATE POLICY gazetteer_zips_read ON "gazetteer_zips" FOR SELECT TO app_user USING (true);
ALTER TABLE "gazetteer_places" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "gazetteer_places" FORCE ROW LEVEL SECURITY;
CREATE POLICY gazetteer_places_read ON "gazetteer_places" FOR SELECT TO app_user USING (true);
REVOKE INSERT, UPDATE, DELETE ON "gazetteer_zips", "gazetteer_places" FROM app_user;
GRANT SELECT ON "gazetteer_zips", "gazetteer_places" TO app_user;
`);
